                check(f"...the status file says so in DXMT's words ({s1.get('state')}, game {s1.get('game')}, generated {s1.get('generated')})",
                      s1.get("state") == "generating" and float(s1.get("generated", "0")) >= 0.85 * float(s1.get("game", "99"))
                      and s1.get("size") == "1280x720" and s1.get("screen") == "120", s1)
                r2, k2, s2 = run("late", "enabled=1\ngenerated=1\nhz=120\n", [120, 50, -1, 1, 150], {"KKH_SRGB": "1"})
