shader_ids = sorted(set(ids(lsfg_m, r"static const struct kk_lsfg_ids kk_lsfg_quality") + ids(lsfg_m, r"static const struct kk_lsfg_ids kk_lsfg_performance")))
STAND_IN = """#include <metal_stdlib>
using namespace metal;
struct descriptor {
    const device void *ptr;
    template<typename T> constant T &as() constant { return reinterpret_cast<constant T &>(this->ptr); }
};
kernel void shader_entry(constant descriptor *descriptors [[buffer(0)]], uint3 tid [[thread_position_in_grid]]) {
%s}
"""
GEN = """    texture2d<float> a = descriptors[16].as<texture2d<float>>(), b = descriptors[17].as<texture2d<float>>();
    texture2d<float, access::read_write> o = descriptors[48].as<texture2d<float, access::read_write>>();
    if (tid.x >= o.get_width() || tid.y >= o.get_height()) return;
    o.write(max(a.read(tid.xy), b.read(tid.xy)), tid.xy);
"""


def container(path):
    """The check's own shaders in the file the app writes: "LSFM", version 1, count, then id, thread group, size, text."""
    parts = []
    for i in shader_ids:
        text = (STAND_IN % (GEN if i == 256 else "    (void)descriptors; (void)tid;\n")).encode()
        parts.append(struct.pack("<5I", i, *((16, 16, 1) if i == 256 else (8, 8, 1)), len(text)) + text)
    path.write_bytes(b"LSFM" + struct.pack("<II", 1, len(parts)) + b"".join(parts))


def judge(err, step, n_want, whole=False, phase=True, tol=3.0):
    """The selftest's lines: (good, the wrong ones). A frame made before frame k lies between frames k-1 and k (present id k + 1),
    at its phase (or halfway, phase=False: the check's own shaders know no time); whole: as wide as the bar."""
    W, BAR = 1280, 64
    center = lambda k: 32 + (k * step) % (W - BAR - 64) + BAR / 2 - 0.5
    good, bad = 0, []
    for m in re.finditer(r"selftest: lsfg picture (\d)/(\d) before frame (\d+) bar at (-?[\d.]+), (\d+) wide, bar (\d+), background (\d+)", err):
        i, n, pid, c, wide, hi, lo = int(m[1]), int(m[2]), int(m[3]), float(m[4]), int(m[5]), int(m[6]), int(m[7])
        k = pid - 1
        if k < 2 or center(k - 1) > center(k) or center(k - 2) > center(k - 1):
            continue   # the bar wrapped at the right edge within the history
        want = center(k - 1) + (center(k) - center(k - 1)) * (i / (n + 1) if phase else 0.5)
        fine = abs(c - want) <= tol and hi >= 230 and lo <= 24 and n == n_want and (not whole or abs(wide - BAR) <= 6)
        good += fine
        if not fine: bad.append((pid, i, n, c, round(want, 1), wide, hi, lo))
    return good, bad


