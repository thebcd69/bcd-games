    mac = subprocess.run(["sw_vers", "-productVersion"], capture_output=True, text=True).stdout.strip() if shutil.which("sw_vers") else ""
    if not mac or int(mac.split(".")[0]) < 26:
        skip(f"the run needs macOS 26 or later (this is {mac or 'not macOS'})")
    else:
        b = [subprocess.run(["xcrun", "clang", "-fno-objc-arc", "-mmacosx-version-min=26.0", "-c", str(tmp / f), "-o", str(tmp / (f + ".o"))],
                            capture_output=True, text=True) for f in ("wsi_common_metal_vti.m", "wsi_common_metal_lsfg.m")]
        b.append(subprocess.run(["xcrun", "clang", "-fobjc-arc", "-mmacosx-version-min=26.0", "-c", str(R / "tests/host/kk_vt_interp_harness.m"),
                                 "-o", str(tmp / "h.o")], capture_output=True, text=True))
        b.append(subprocess.run(["xcrun", "clang", str(tmp / "wsi_common_metal_vti.m.o"), str(tmp / "wsi_common_metal_lsfg.m.o"), str(tmp / "h.o"),
                                 "-framework", "Metal", "-framework", "QuartzCore", "-framework", "CoreVideo", "-framework", "CoreMedia",
                                 "-framework", "VideoToolbox", "-framework", "Foundation", "-o", str(tmp / "kkh")], capture_output=True, text=True))
        check("the module and the harness build for this Mac", all(x.returncode == 0 for x in b), "\n".join(x.stderr for x in b))
        container(tmp / "stand-in.bin")

        def run(name, ctl, args, env=None, msl=None):
            (tmp / f"{name}.ctl").write_text(ctl)
            e = {k: v for k, v in os.environ.items() if not k.startswith(("MADEIRA_", "KKH_"))}
            e.update({"MADEIRA_LSFG_HOST_CTL": str(tmp / f"{name}.ctl"), "MADEIRA_LSFG_HOST_MSL": str(msl or tmp / "stand-in.bin"),
                      "MADEIRA_KK_VTI_SELFTEST": "1", "MADEIRA_VT_PANEL_HZ": "120"})
            e.update(env or {})
            r = subprocess.run([str(tmp / "kkh"), *map(str, args)], capture_output=True, text=True, env=e, timeout=240)
            kv = dict(l.split("=", 1) for l in r.stdout.splitlines() if "=" in l and " " not in l.split("=", 1)[0])
            status = (tmp / f"{name}.ctl.status").read_text() if (tmp / f"{name}.ctl.status").exists() else ""
            return r, kv, dict(l.split("=", 1) for l in status.splitlines() if "=" in l)

        if all(x.returncode == 0 for x in b):
            r1, k1, s1 = run("on", "enabled=1\ngenerated=1\nhz=120\n", [120, 33, -1, 1])
