"""Lossless Scaling frame generation in KosmicKrisp's present (build 706; wsi_common_metal_lsfg.m in
build/mesa-ios/playport-patches/0036-*.patch).

Checks, on the code the patch adds (taken out of the patch itself):
  1. the file: GPL-3.0-or-later with Porthole's and lsfg-vk's notices, and no part of Lossless Scaling in it (no DXBC, nothing
     vkd3d-shader wrote); the chain of passes is DXMT's (tools/patch-dxmt-lsfg.py): the same shader ids for both layouts, the
     same number of dispatches in each pass, the same rule for when frames are made, the same control and status files;
  2. it compiles for iOS 26 (arm64, the iPhone SDK) with -Wall -Wextra -Werror and nothing of it is visible outside the library;
  3. on this Mac, a real run of KosmicKrisp's stand-ins and worker (kk_vt_interp_harness.m) with shaders of this check's own (the
     generate pass takes the brighter of the frame before and this one, so a made frame shows both bars as one, centred between
     them; every other pass does nothing; Lossless Scaling's are not in BCD):
       - every frame of a game slower than the screen gets one made frame, presented before it, made of its two neighbours;
         an sRGB swapchain and a GPU 150 ms behind the same; the status file says so in DXMT's words;
       - the control file switched off: no more frames, the status says off, the game goes on at its pace;
       - shaders missing: the status says why, the game goes on; a game faster than the screen: no frames;
     (skipped where this Mac has no Metal 4 queue);
  4. with --lsfg-msl <file> (the person's own shaders as the app translates them; never in the repository): every frame made
     lies between its two frames, whole, with the bar moving further than it is wide (motion, not a blend);
  5. wiring: THIRD-PARTY-NOTICES, the app's side (the host paths, one frame generator a session), docs.

    tests/host/check-kk-lsfg.py [--require-run] [--lsfg-msl <file>]
"""
