def new_file(name):
    part = diff[diff.index(f"diff --git a/{name} b/{name}"):]
    nxt = part.find("\ndiff --git ", 1)
    part = part if nxt < 0 else part[:nxt + 1]
    body = part[part.index("\n@@ "):]
    return "\n".join(l[1:] for l in body.split("\n")[2:] if l.startswith("+")) + "\n"


