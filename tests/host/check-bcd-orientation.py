"""The screen orientation lock for a game's session (BCDOrientation.swift, BCDOrientationLive.swift).

Opt-in: off is today's behaviour. Settings › Graphics › Screen orientation (bcd.cfg `orientation-lock`) and a game's
page (its library entry's `orientationLock`) choose "follow the device" (the default), "landscape" or a landscape with the
camera on a side; the game's own choice wins. While a library session runs and the choice is a landscape, the interface
stays in landscape whatever the device's position, and it follows the device again when the session ends. Checks:
  1. The choice and the rule, compiled on the host (BCDOrientation.swift without its UIKit part) and run: the words, the
     default, an unknown word, every pair of Settings and game words, the game page's list.
  2. The UIKit part, type-checked against the iOS simulator SDK: the app delegate, the lock, the mask of each choice.
  3. Off changes nothing: the delegate's answer with no lock is the three orientations Info.plist declares (Info.plist is
     read here and compared); Info.plist and the device families are as they were (no UIRequiresFullScreen added); the
     engine side reaches UIKit only when a choice locks or a lock is on; no key, no game choice: no call, no log line.
  4. The wiring: the app adopts the delegate; the session start and end call the engine side once each; the setting is
     read as bcd.cfg's `orientation-lock`; Settings' Graphics and the game page have the row, the live backends write only
     the words the choice knows; the library entry's field is optional (older files decode); the Xcode project builds both
     files; the preview leaves the engine side out and adopts the delegate; the settings catalog's generator describes the
     key (the catalog itself is regenerated by the lead).
  5. The simulator proof the author took (iOS 26.3 and 18.1 phones): the mapping of the two sides is the one in the file.
tests/host/check-bcd-orientation.py [--require-swift]
"""
import argparse
import plistlib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

R = Path(__file__).resolve().parents[2]
APP = R / "app/Madeira"
ap = argparse.ArgumentParser()
ap.add_argument("--require-swift", action="store_true")
args = ap.parse_args()
ok = True


def check(what, cond, detail=""):
    global ok
    print(("ok   " if cond else "FAIL ") + what + (("\n     " + str(detail)[-3000:]) if detail and not cond else ""))
    ok = ok and bool(cond)


def note(text):
    print("note " + text)


src = (APP / "BCDOrientation.swift").read_text()
live = (APP / "BCDOrientationLive.swift").read_text()
check("both files have the BCD licence header",
      all("SPDX-License-Identifier: GPL-3.0-only" in t[:300] and "LICENSE-BCD.md" in t[:400] for t in (src, live)))

# ---------------------------------------------------------------- 1 and 2. Swift
xcrun = shutil.which("xcrun")
if not xcrun:
    check("xcrun swiftc is here for the Swift parts", not args.require_swift)
else:
    with tempfile.TemporaryDirectory(prefix="bcd-orientation-") as t:
        t = Path(t)
        (t / "Main.swift").write_text((Path(__file__).resolve().parent / "bcd_orientation_checks.swift").read_text())
        r = subprocess.run(["xcrun", "swiftc", "-parse-as-library", "-swift-version", "5", "-o", str(t / "run"),
                            str(t / "Main.swift"), str(APP / "BCDOrientation.swift")], capture_output=True, text=True)
        check("the choice and the rule compile on the host", r.returncode == 0, r.stderr)
        if r.returncode == 0:
            r = subprocess.run([str(t / "run")], capture_output=True, text=True)
            print(r.stdout, end="")
            check("the choice and the rule behave", r.returncode == 0, r.stdout + r.stderr)
        sdk = subprocess.run(["xcrun", "--sdk", "iphonesimulator", "--show-sdk-path"], capture_output=True, text=True).stdout.strip()
        arch = "arm64" if subprocess.run(["uname", "-m"], capture_output=True, text=True).stdout.strip() == "arm64" else "x86_64"
        r = subprocess.run(["xcrun", "swiftc", "-typecheck", "-swift-version", "5", "-target", arch + "-apple-ios18.0-simulator", "-sdk", sdk,
                            str(APP / "BCDOrientation.swift")], capture_output=True, text=True)
        check("the UIKit part (app delegate, lock, masks) type-checks against the iOS SDK", r.returncode == 0, r.stderr)

# ---------------------------------------------------------------- 3. off changes nothing
plist = plistlib.loads((APP / "Info.plist").read_bytes())
declared = {"UIInterfaceOrientationPortrait": "portrait", "UIInterfaceOrientationLandscapeLeft": "landscapeLeft",
            "UIInterfaceOrientationLandscapeRight": "landscapeRight"}
plist_set = {declared[o] for o in plist["UISupportedInterfaceOrientations"]}
m = re.search(r"let bcdDeclaredOrientations: UIInterfaceOrientationMask = \[([^\]]*)\]", src)
check("the answer with no lock is the three orientations Info.plist declares",
      m is not None and {w.strip().lstrip(".") for w in m.group(1).split(",")} == plist_set, (plist_set, m.group(1) if m else None))
check("the delegate answers with the lock's `supported`, which is the declared set until a choice locks",
      "BCDOrientationLock.shared.supported" in src and "choice.mask ?? bcdDeclaredOrientations" in src)
check("Info.plist has no UIRequiresFullScreen and no iPad orientation key of its own (nothing is declared differently)",
      "UIRequiresFullScreen" not in plist and "UISupportedInterfaceOrientations~ipad" not in plist)
check("apply() does nothing for the choice already in force, except that a lock in force looks at the scenes again (night round 2026-11-11, A5 S15)",
      "guard new != choice else {" in src and 'if new.locked { reassert(reason: "start") }' in src)
check("the lock reaches UIKit only when it turns on or off or looks again while locked (the first call of apply with .free returns before any UIKit call)",
      src.index("guard new != choice else {") < src.index("UIDevice.current") < src.index("requestGeometryUpdate")
      and "guard choice.locked, let mask = choice.mask else { return }" in src)
check("A5 S15: a scene that already has an orientation the lock allows is left alone (only the log line); a scene that does not is asked again",
      "guard !fits else { continue }" in src and "BCDOrientationRules.allows(mask: mask.rawValue, interfaceRaw: raw)" in src
      and src.index("guard !fits else { continue }") < src.index("scene.requestGeometryUpdate", src.index("func reassert(")))
check("A5 S15: the activation observer exists only while a lock is on (added when it turns on, removed when it ends)",
      "if new.locked { watchActivation() } else { unwatchActivation() }" in src and "UIApplication.didBecomeActiveNotification" in src
      and src.count("NotificationCenter.default.addObserver") == 1)
check("the engine side does nothing when the choice is the device's and no lock is on",
      "guard chosen.locked || lock.choice.locked else { return }" in live and "guard lock.choice.locked else { return }" in live)
check("the lock logs when it changes, and one `[orientation] check:` line per scene when a lock in force is looked at again (never without a lock)",
      src.count("onLog?(") == 4 and "[orientation]" in src and "[orientation] check: lock=" in src)
check("a lock that ends turns the interface to the way the device is held (UIKit leaves it where it is)",
      "device.orientation.interfaceMask" in src and "case .landscapeLeft: return .landscapeRight" in src)
check("the two sides: camera on the left is the interface's landscapeRight, camera on the right its landscapeLeft (proved in the simulator)",
      "case .landscapeCameraLeft: return .landscapeRight" in src and "case .landscapeCameraRight: return .landscapeLeft" in src)

# 2026-10-24 (ajan28): the `[device] window:` line of a launch, log only: what a player's log needs to say why BCD's window can or cannot
# be resized on an iPad (the scene against the screen, size restrictions, the orientations declared). It reads the scenes and the bundle's
# Info.plist and changes nothing.
current = src[src.index("extension BCDWindowReport {"):]
current = current[:current.index("\n}\n") + 3]
check("the window line only reads: no geometry request, no setter, no orientation call",
      not re.search(r"requestGeometryUpdate|setNeedsUpdate|\.apply\(|sizeRestrictions\??\.(min|max)|\bnotification|NotificationCenter|\.windows\b", current), current)
check("each launch logs it once, right after the device launch line, on the main thread (ContentView's start sequence)",
      (APP / "ContentView.swift").read_text().count("BCDWindowReport.current()") == 1
      and "DeviceDiagnostics.logLaunch()\n        logStore.log(BCDWindowReport.current())" in (APP / "ContentView.swift").read_text()
      and "@MainActor static func current() -> String" in current)
check("it names the Info.plist facts the diagnosis needs, from the bundle (nothing is declared by this line)",
      'info["UIRequiresFullScreen"]' in current and 'info["UISupportedInterfaceOrientations"]' in current and "BCDOrientationLock.shared.supported" in current)

# ---------------------------------------------------------------- 4. the wiring
app = (APP / "MadeiraApp.swift").read_text()
check("the app adopts the delegate once", app.count("@UIApplicationDelegateAdaptor(BCDOrientationDelegate.self)") == 1)
lib = (APP / "Library.swift").read_text()
check("a session start calls the engine side once, in begin(), and an end once, in finish()",
      lib.count("BCDOrientationLive.sessionBegan(entry)") == 1 and lib.count("BCDOrientationLive.sessionEnded()") == 1
      and lib.index("func begin(_ entry: LibraryEntry") < lib.index("BCDOrientationLive.sessionBegan(entry)") < lib.index("private func poll()")
      and lib.index("private func finish()") < lib.index("BCDOrientationLive.sessionEnded()") < lib.index("fputs(\"[frontend] returned to library"))
check("the library entry's choice is an optional string, so older library files decode", "var orientationLock: String?" in lib)
check("the setting is bcd.cfg's orientation-lock, read as MadeiraConfig.get(\"orientation-lock\")",
      'MadeiraConfig.get("orientation-lock")' in live and 'static let key = "orientation-lock"' in live)
check("a session's choice is the game's own, else Settings'", "BCDOrientationRules.effective(global: global, game: entry.orientationLock)" in live)
sections = (APP / "BCDSettingsSections.swift").read_text()
settings_live = (APP / "BCDSettingsLive.swift").read_text()
sample = (R / "app/BCDPreview/BCDSettingsPreviewData.swift").read_text()
check("Settings › Graphics has the Screen orientation row, with the four choices",
      'title: "Screen orientation"' in sections and "BCDOrientationChoice.offered.map" in sections and "backend.setOrientation($0)" in sections)
check("the Graphics backends (the app's and the preview's) both have it",
      "func setOrientation(_ value: String)" in sections and "func setOrientation(" in settings_live and "func setOrientation(" in sample)
check("the app's backend writes only a word the choice knows, and off is the key removed",
      "write(BCDLiveKey.orientation, BCDOrientationChoice(setting: value).setting)" in settings_live)
page = (APP / "BCDGamePageLive.swift").read_text()
check("the game page has the Screen orientation setting, with Settings' choice named",
      'id: "orientation", title: "Screen orientation"' in page and "BCDOrientationRules.gameChoices(global: BCDOrientationLive.global)" in page)
check("... and saves only a word the choice knows to the entry, \"\" for the entry's own none",
      'case "orientation":' in page and "BCDOrientationChoice(rawValue: value) != nil" in page and "$0.orientationLock = value.isEmpty ? nil : value" in page)
check("the preview's game page has the setting too", 'choice("orientation", "Screen orientation"' in (R / "app/BCDPreview/BCDGamePageSample.swift").read_text())
pbx = (R / "app/Madeira.xcodeproj/project.pbxproj").read_text()
check("the Xcode project builds both files", all(f"{n} in Sources" in pbx and pbx.count(n) >= 4 for n in ("BCDOrientation.swift", "BCDOrientationLive.swift")))
prev = (R / "tools/ui-preview.py").read_text()
check("the preview build leaves the engine side out and keeps the choice and the lock",
      'ENGINE_BOUND |= {"BCDOrientationLive.swift"}' in prev and "BCDOrientation.swift" not in re.search(r"ENGINE_BOUND = \{[^}]*\}", prev).group(0))
check("the preview app adopts the delegate and can turn the lock on (-BCDOrientationLock) for a simulator run",
      "@UIApplicationDelegateAdaptor(BCDOrientationDelegate.self)" in (R / "app/BCDPreview/BCDPreviewApp.swift").read_text()
      and "BCDOrientationLock" in (R / "app/BCDPreview/BCDPreviewApp.swift").read_text())
gen = (R / "build/tools/gen-config-catalog.py").read_text()
check("the catalog generator describes orientation-lock (the lead regenerates the catalog)", '"orientation-lock": {' in gen and "landscape-camera-left" in gen)
check("no Madeira in what a person reads", "Madeira" not in re.sub(r"//[^\n]*", "", src))
wf = (R / ".github/workflows/build-ipa.yml").read_text()
check("the workflow runs this check", "tests/host/check-bcd-orientation.py" in wf)
sys.exit(0 if ok else 1)
